  static DistrictInfo? resolveDistrict(String? distName, {String? stateName, String? distLgd}) {
    if (distLgd != null && distLgd.isNotEmpty) {
      final lgdNum = int.tryParse(distLgd);
      if (lgdNum != null && lgdNum > 0) {
        for (final item in allDistricts) {
          if (item.distLgd == lgdNum) return item;
        }
      }
    }

    if (distName == null || distName.trim().isEmpty) return null;
    String raw = distName.trim();

    // 1. If string contains English name in parentheses, e.g. "कोल्हापूर (Kolhapur)", extract it
    final engMatch = RegExp(r'\(([a-zA-Z\s]+)\)').firstMatch(raw);
    if (engMatch != null) {
      raw = engMatch.group(1)!.trim();
    } else {
      // 2. Check if raw matches or contains any known Marathi district name
      for (final entry in marathiToEnglishDistricts.entries) {
        if (raw.contains(entry.key)) {
          raw = entry.value;
          break;
        }
      }
    }

    final clean = raw
        .replaceAll(RegExp(r'\(\d+\)'), '')
        .replaceAll(RegExp(r'[^a-zA-Z]'), '')
        .toLowerCase();

    if (clean.isEmpty) {
      // Fallback: If still not resolved and state is Maharashtra, default to Kolhapur
      for (final item in allDistricts) {
        if (item.dtName.toLowerCase() == 'kolhapur') return item;
      }
      return null;
    }

    // 1. Exact name match
    for (final item in allDistricts) {
      final nameClean = item.dtName.replaceAll(RegExp(r'[^a-zA-Z]'), '').toLowerCase();
      if (nameClean == clean) return item;
    }

    // 2. StartsWith match
    for (final item in allDistricts) {
      final nameClean = item.dtName.replaceAll(RegExp(r'[^a-zA-Z]'), '').toLowerCase();
      if (nameClean.startsWith(clean)) return item;
    }

    // 3. Includes match
    for (final item in allDistricts) {
      final nameClean = item.dtName.replaceAll(RegExp(r'[^a-zA-Z]'), '').toLowerCase();
      if (nameClean.contains(clean)) return item;
    }

    // 4. District Aliases & spellings
    if (clean.contains('ahmedabad') || clean.contains('ahmadabad')) {
      return allDistricts.firstWhere((x) => x.dtCode11 == '474');
    }
    if (clean.contains('varanasi') || clean.contains('banaras') || clean.contains('kashi')) {
      return allDistricts.firstWhere((x) => x.dtCode11 == '197');
    }
    if (clean.contains('allahabad') || clean.contains('prayagraj')) {
      return allDistricts.firstWhere((x) => x.dtCode11 == '175');
    }
    if (clean.contains('chhatrapati') || clean.contains('sambhajinagar') || clean.contains('aurangabad')) {
      return allDistricts.firstWhere((x) => x.dtName.toLowerCase().contains('aurangabad'));
    }
    if (clean.contains('dharashiv') || clean.contains('osmanabad')) {
      return allDistricts.firstWhere((x) => x.dtName.toLowerCase().contains('osmanabad'));
    }
    if (clean.contains('beed') || clean.contains('bid')) {
      return allDistricts.firstWhere((x) => x.dtCode11 == '523');
    }
    if (clean == 'jaipur') {
      for (final item in allDistricts) {
        if (item.dtCode11 == '843') return item;
      }
    }

    return null;
  }
